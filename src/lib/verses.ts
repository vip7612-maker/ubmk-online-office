/**
 * 오늘의 구절. 몽골 현지시간(UTC+8)의 날짜를 기준으로 고른다.
 * 서버에서 계산해 내려보내므로 화면이 깜빡이거나 사람마다 달라지지 않는다.
 */
export function verseOfTheDay(now: Date = new Date()): Verse {
  const local = new Date(now.getTime() + 8 * 60 * 60 * 1000); // Asia/Ulaanbaatar
  const start = Date.UTC(local.getUTCFullYear(), 0, 1);
  const dayOfYear = Math.floor((local.getTime() - start) / 86_400_000);
  // 해가 바뀌어도 같은 날짜에 같은 구절이 되지 않도록 연도를 섞는다.
  const index = (dayOfYear + local.getUTCFullYear() * 7) % VERSES.length;
  return VERSES[index];
}
